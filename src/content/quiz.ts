/** Сколько вопросов в одной попытке. Если пул меньше — берём весь пул. */
export const ATTEMPT_SIZE = 10;

/** Порог сдачи — 80% верных ответов, округляя вверх. */
export const passMark = (total: number) => Math.ceil(total * 0.8);

const shuffle = <T,>(list: T[]): T[] => {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
};

/** Случайная выборка вопросов с перемешанными вариантами.
 *  Собирается один раз на попытку: пересдача даёт другой набор. */
export function buildAttempt(slug: string, size = ATTEMPT_SIZE): Question[] {
  const list = pool[slug] ?? [];
  return shuffle(list)
    .slice(0, Math.min(size, list.length))
    .map((q) => {
      const order = shuffle(q.a.map((_, i) => i));
      return {
        ...q,
        a: order.map((i) => q.a[i]),
        correct: order.indexOf(q.correct),
      };
    });
}

export const poolSize = (slug: string) => (pool[slug]?.length ?? 0);
export const hasQuiz = (slug: string) => poolSize(slug) > 0;
export const attemptSizeFor = (slug: string) => Math.min(ATTEMPT_SIZE, poolSize(slug));
